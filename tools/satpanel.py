"""Shared parts of the satellite panels (WING-DYN, WING-KNOBS …): a panel of any width in the WING-LINK look,
its real SVG + layout header, its preview with Rack components. (WING-EQ: tools/wingeq_panel.py, the pattern.)"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
if len(sys.argv) > 3:
    os.environ["RACK"] = sys.argv[3]
import panelkit as wl  # noqa: E402

ROOT = wl.ROOT
H = 128.5


class SatPanel(wl.Panel):
    def __init__(self, ns, hp):
        super().__init__(ns)
        self.hp = hp
        self.W = hp * 5.08

    def header(self, title, subtitle):
        W, H_ = self.W, H
        self.e(f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{W:.2f}mm" '
               f'height="{H_}mm" viewBox="0 0 {W:.2f} {H_}">')
        self.e(f'<rect width="{W:.2f}" height="{H_}" fill="{wl.BG}"/>')
        if not title:
            return
        self.text(12.9 if W > 60 else 4.0, 7.6, title, 5.1 if W > 60 else 4.0, wl.TITLE, 800, "start", 1.08 if W > 60 else 0.6)
        if subtitle:
            x = (12.9 if W > 60 else 4.0) + wl.width(title, 5.1 if W > 60 else 4.0, 800, 1.08 if W > 60 else 0.6) + 3.4
            self.text(x, 7.45, subtitle, 1.76, wl.DIM, 600, "start", 0.47)

    def mknob(self, name, x, y):
        self.comps.append(("medium", name, x, y))
        self.e(f'<circle cx="{x:.2f}" cy="{y}" r="{4.8 + 0.88:.2f}" fill="none" stroke="{wl.RING}" stroke-width="0.29" '
               f'stroke-dasharray="0.29 0.73" stroke-linecap="round"/>')

    def sbutton(self, name, x, y):
        self.comps.append(("sbutton", name, x, y))

    def tri(self, x, y, left):
        d = -1 if left else 1
        self.e(f'<path d="M{x - 0.8 * d:.2f} {y - 0.9:.2f} L{x + 0.8 * d:.2f} {y:.2f} L{x - 0.8 * d:.2f} {y + 0.9:.2f} Z" '
               f'fill="{wl.TXT}"/>')

    def plate(self, x, y, w, h, title=None, col=None):
        self.e(f'<rect x="{x:.2f}" y="{y}" width="{w:.2f}" height="{h}" rx="1" fill="{wl.PLATE}"/>')
        self.e(f'<rect x="{x:.2f}" y="{y}" width="{w:.2f}" height="0.75" rx="0.35" fill="{col or wl.ACC}"/>')
        if title:
            self.text(x + 1.8, y + 4.7, title, 1.65, col or wl.ACC, 800, "start", 0.35)

    def dark(self, x, y, w, h, name=None):
        self.e(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1" fill="{wl.DARK}" stroke="{wl.LINE}" stroke-width="0.3"/>')
        if name:
            self.area(name, x, y, w, h)


def write_real(p, svg, header, ns, tool):
    p.finish()
    open(os.path.join(ROOT, "res", svg), "w").write("\n".join(p.out))
    lines = [f"// Generated by tools/{tool} - do not edit", "#pragma once", f"namespace {ns} {{"]
    for kind, n, x, y in p.comps:
        lines.append(f"static const float {n}[2] = {{{x:.3f}f, {y:.3f}f}};")
    for n, (x, y, w, h) in p.areas.items():
        lines.append(f"static const float {n}[4] = {{{x:.3f}f, {y:.3f}f, {w:.3f}f, {h:.3f}f}};")
    lines += [f"static const int HP = {p.hp};", "}"]
    open(os.path.join(ROOT, "src", header), "w").write("\n".join(lines) + "\n")
    print("wrote res/" + svg + " and src/" + header)


def write_preview(p, mock, out):
    """mock(o, put): draws the display content (o: the SVG lines, put(s, x, y, size, colour, weight, anchor))."""
    p.finish()
    o = p.out
    KNOB = os.path.join(ROOT, "res", "knob")
    for kind, n, x, y in p.comps:
        if kind in ("small", "medium"):
            wl.img(o, "", x, y, os.path.join(KNOB, kind + "_bg.svg"))
            wl.img(o, "", x, y, os.path.join(KNOB, kind + ".svg"))
        elif kind == "button":
            wl.img(o, "VCVBezel", x, y)
        elif kind == "sbutton":
            wl.img(o, "VCVButton_0", x, y)
        else:
            wl.img(o, "PJ301M", x, y)
    for sx_ in ((7.62, p.W - 7.62) if p.W > 30 else (7.62,)):
        for sy in (2.54, H - 2.54):
            wl.img(o, "ScrewBlack", sx_, sy)

    def put(s, x, y, size, c, wt, anchor="middle", sp=0.15):
        n0 = len(o)
        p.text(x, y, s, size, c, wt, anchor, sp)
        if len(o) > n0:
            o.insert(-1, o.pop(n0))

    mock(o, put)
    svg = out.rsplit(".", 1)[0] + ".svg"
    open(svg, "w").write("\n".join(o))
    subprocess.run(["rsvg-convert", "-w", str(int(p.W * 11)), svg, "-o", out], check=True)
    os.remove(svg)
    print("wrote", out)
