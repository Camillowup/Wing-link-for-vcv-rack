#!/usr/bin/env python3
"""Panel of WING-FX, the expander for the WING's effects (in the look of the GENRA plugin).

Four FX slots side by side (SLOTS − / + pages through all 16): the slot's head (number, PREMIUM / STANDARD, ON), the
model (a click opens the list), MIX and four parameters (their names come with the model: the module draws them),
CV for MIX and the four; at the bottom CLOCK in, TAP, SYNC and CLOCK out.

Usage:  wingfx_panel.py real                   -> res/WingFx.svg + src/WingFxLayout.hpp
        wingfx_panel.py preview OUT.png [RACK] -> preview with Rack components and a mock display
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
if PREVIEW_RACK := (sys.argv[3] if len(sys.argv) > 3 else None):
    os.environ["RACK"] = PREVIEW_RACK
import panelkit as wl  # noqa: E402  (fonts, colours, Panel, img)

MODE = sys.argv[1] if len(sys.argv) > 1 else "real"
PREVIEW = MODE == "preview"
ROOT = wl.ROOT
HP = 24
W, H = HP * 5.08, 128.5
SP = 28.0
X0 = (W - 4 * SP) / 2


class FxPanel(wl.Panel):
    def header(self, title, subtitle):
        self.e(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.2f}mm" height="{H}mm" viewBox="0 0 {W:.2f} {H}">')
        self.e(f'<rect width="{W:.2f}" height="{H}" fill="{wl.BG}"/>')
        self.text(12.9, 7.6, title, 5.1, wl.TITLE, 800, "start", 1.08)
        self.text(12.9 + wl.width(title, 5.1, 800, 1.08) + 3.4, 7.45, subtitle, 1.76, wl.DIM, 600, "start", 0.47)

    def mknob(self, name, x, y):
        self.comps.append(("medium", name, x, y))
        self.e(f'<circle cx="{x:.2f}" cy="{y}" r="{4.8 + 0.88:.2f}" fill="none" stroke="{wl.RING}" stroke-width="0.29" '
               f'stroke-dasharray="0.29 0.73" stroke-linecap="round"/>')


p = FxPanel("fx")
p.header("WING-FX", "EXPANDER · WING EFFECTS")
DISP = (X0 + 0.4, 10.6, 74.0, 11.2)
p.e(f'<rect x="{DISP[0]:.2f}" y="{DISP[1]}" width="{DISP[2]}" height="{DISP[3]}" rx="1" fill="{wl.DARK}" '
    f'stroke="{wl.LINE}" stroke-width="0.3"/>')
p.area("DISPLAY", *DISP)
bx = DISP[0] + DISP[2]
p.button("PAGE_DOWN", bx + 5.2, 15.4)
p.button("PAGE_UP", bx + 22.7, 15.4)
p.text(bx + 13.95, 9.2, "SLOTS", 1.4, wl.DIM, 700, "middle", 0.25)
p.text(bx + 5.2, 21.6, "−", 1.9, wl.TXT, 800)
p.text(bx + 22.7, 21.6, "+", 1.9, wl.TXT, 800)
p.e(f'<rect x="{bx + 10.8:.2f}" y="12.2" width="6.3" height="6.4" rx="0.8" fill="{wl.DARK}" stroke="{wl.LINE}" stroke-width="0.3"/>')
p.area("STEP", bx + 10.8, 12.2, 6.3, 6.4)  # the step (1 or 4): the module writes it; a click switches
p.text(bx + 13.95, 21.6, "STEP", 1.3, wl.DIM, 700, "middle", 0.2)

for i in range(4):
    n = i + 1
    x0 = X0 + i * SP
    cx = x0 + SP / 2
    p.e(f'<rect x="{x0 + 0.4:.2f}" y="23.5" width="{SP - 0.8:.2f}" height="84.6" rx="1.2" fill="{wl.PLATE}"/>')
    p.area(f"HEAD{n}", x0 + 0.4, 23.5, SP - 0.8, 6.6)       # slot number, PREMIUM / STANDARD, colour bar (drawn)
    p.button(f"ON{n}", x0 + SP - 5.2, 27.6)
    p.e(f'<rect x="{x0 + 1.4:.2f}" y="32.0" width="{SP - 2.8:.2f}" height="13.4" rx="0.8" fill="{wl.DARK}"/>')
    p.area(f"MODEL{n}", x0 + 1.4, 32.0, SP - 2.8, 13.4)        # the model: a click opens the list
    p.knob(f"MIX{n}", cx, 51.0)
    p.text(cx, 57.9, "MIX", 1.5, wl.TXT, 700, "middle", 0.3)
    for k, (dx, y) in enumerate(((-6.2, 63.5), (6.2, 63.5), (-6.2, 78.5), (6.2, 78.5))):
        p.knob(f"P{k + 1}_{n}", cx + dx, y)
        p.area(f"LBL{k + 1}_{n}", cx + dx - 6.0, y + 4.9, 12.0, 5.2)   # name and value (drawn)
    p.e(f'<line x1="{x0 + 2:.2f}" y1="88.6" x2="{x0 + SP - 2:.2f}" y2="88.6" stroke="{wl.LINE}" stroke-width="0.3"/>')
    for k, (dx, y, lb) in enumerate(((-8.9, 93.6, "MIX"), (0, 93.6, "P1"), (8.9, 93.6, "P2"), (-4.45, 104.0, "P3"),
                                     (4.45, 104.0, "P4"))):
        p.jack(f"CV{k}_{n}", cx + dx, y, lb)

# the bottom: tempo
FY = 117.9
p.e(f'<rect x="12.0" y="110.4" width="{W - 24:.2f}" height="15.6" rx="1.2" fill="{wl.PLATE}"/>')
gx = X0 + 4 * SP / 2
p.jack("CLOCK_IN", gx - 36, FY, "CLOCK IN")
p.button("TAP", gx - 18, FY)
p.text(gx - 18, FY + 5.45, "TAP", 1.3, wl.DIM, 600, "middle", 0.15)
p.button("SYNC", gx, FY)
p.text(gx, FY + 5.45, "SYNC", 1.3, wl.ACC, 800, "middle", 0.15)
p.area("TEMPO", gx + 8, FY - 3.4, 16, 6.8)
p.e(f'<rect x="{gx + 8:.2f}" y="{FY - 3.4:.2f}" width="16" height="6.8" rx="0.8" fill="{wl.DARK}"/>')
p.text(gx + 16, FY + 5.45, "BPM", 1.3, wl.DIM, 600, "middle", 0.15)
p.jack("CLOCK_OUT", gx + 36, FY, "CLOCK OUT", True)
p.finish()

if not PREVIEW:
    open(os.path.join(ROOT, "res", "WingFx.svg"), "w").write("\n".join(p.out))
    lines = ["// Generated by tools/wingfx_panel.py - do not edit", "#pragma once", "namespace fxlayout {"]
    for kind, n, x, y in p.comps:
        lines.append(f"static const float {n}[2] = {{{x:.3f}f, {y:.3f}f}};")
    for n, (x, y, w, h) in p.areas.items():
        lines.append(f"static const float {n}[4] = {{{x:.3f}f, {y:.3f}f, {w:.3f}f, {h:.3f}f}};")
    lines += [f"static const int HP = {HP};", "}"]
    open(os.path.join(ROOT, "src", "WingFxLayout.hpp"), "w").write("\n".join(lines) + "\n")
    print("wrote res/WingFx.svg and src/WingFxLayout.hpp")
    sys.exit(0)

# ---------------------------------------------------------------- preview
o = p.out
KNOB = os.path.join(ROOT, "res", "knob")
for kind, n, x, y in p.comps:
    if kind in ("small", "medium"):
        wl.img(o, "", x, y, os.path.join(KNOB, kind + "_bg.svg"))
        wl.img(o, "", x, y, os.path.join(KNOB, kind + ".svg"))
    elif kind == "button":
        wl.img(o, "VCVBezel", x, y)
    else:
        wl.img(o, "PJ301M", x, y)
for sx_ in (7.62, W - 7.62):
    for sy in (2.54, H - 2.54):
        wl.img(o, "ScrewBlack", sx_, sy)
MOCK = [("HALL", "PREMIUM", "#ff6b5b", [("DECAY", "2.4 s"), ("PRE", "20 ms"), ("SIZE", "60"), ("DAMP", "8k0")]),
        ("ST-DL", "PREMIUM", "#3dc9ff", [("TIME", "484 ms"), ("FEED", "35 %"), ("FB HC", "4k5"), ("HC", "12k")]),
        ("PLATE", "PREMIUM", "#e0779e", [("DECAY", "1.6 s"), ("PRE", "0 ms"), ("SIZE", "40"), ("DAMP", "6k0")]),
        ("CHORUS", "PREMIUM", "#b8f23a", [("SPEED", "0.8 Hz"), ("DEPTH L", "40 %"), ("DEPTH R", "45 %"), ("SPREAD", "60")])]


def put(s, x, y, size, c, wt, anchor="middle", sp=0.15):
    n0 = len(o)
    p.text(x, y, s, size, c, wt, anchor, sp)
    if len(o) > n0:
        o.insert(-1, o.pop(n0))


for i, (mdl, tag, col, prm) in enumerate(MOCK):
    x, y, w, h = p.areas[f"HEAD{i + 1}"]
    o.insert(-1, f'<rect x="{x}" y="{y}" width="{w}" height="0.9" rx="0.45" fill="{col}"/>')
    put(f"FX {i + 1}", x + 1.4, y + 4.4, 2.1, col, 800, "start", 0.5)
    put(tag, x + 9.6, y + 4.2, 1.3, "#ffd84a", 800, "start", 0.25)
    x, y, w, h = p.areas[f"MODEL{i + 1}"]
    put(mdl, x + 1.5, y + 4.0, 2.1, "#ffffff", 800, "start", 0.3)
    o.insert(-1, f'<path d="M{x + w - 3.4:.2f} {y + 2.2:.2f} h2.2 l-1.1 1.4 z" fill="#5d606b"/>')
    # the effect's picture (the module draws it from the knobs)
    import math
    gx, gy, gw, gh = x + 1.2, y + 5.6, w - 2.4, h - 6.6
    base = gy + gh
    o.insert(-1, f'<line x1="{gx}" y1="{base:.2f}" x2="{gx + gw}" y2="{base:.2f}" stroke="#34363f" stroke-width="0.2"/>')
    if mdl in ("HALL", "PLATE"):
        dec = 1.0 if mdl == "HALL" else 0.6
        st = gx + (2.4 if mdl == "HALL" else 1.6)
        o.insert(-1, f'<rect x="{gx + 0.3:.2f}" y="{gy + 0.4:.2f}" width="0.7" height="{gh - 0.4:.2f}" fill="#f2f3f7"/>')
        pts = " ".join(f"{st + u / 40 * (gx + gw - st):.2f},{base - (gh - 0.6) * math.exp(-u / 40 * 3.2 / dec):.2f}" for u in range(41))
        o.insert(-1, f'<polygon points="{st:.2f},{base:.2f} {pts} {gx + gw:.2f},{base:.2f}" fill="{col}" fill-opacity="0.22"/>')
        o.insert(-1, f'<polyline points="{pts}" fill="none" stroke="{col}" stroke-width="0.35"/>')
    elif mdl == "ST-DL":
        hh, k = gh - 0.6, 0
        while gx + 0.6 + k * 3.9 < gx + gw:
            o.insert(-1, f'<rect x="{gx + 0.6 + k * 3.9:.2f}" y="{base - hh:.2f}" width="0.8" height="{hh:.2f}" fill="{col if k % 2 == 0 else "#c9ccd4"}"/>')
            hh *= 0.65
            k += 1
    else:
        mid = gy + gh / 2
        for ph, c2, wd in ((0, col, 0.35), (1.57, "#c9ccd4", 0.28)):
            pts = " ".join(f"{gx + u / 60 * gw:.2f},{mid + math.sin(u / 60 * 2 * math.pi * 2.2 + ph) * gh * 0.42:.2f}" for u in range(61))
            o.insert(-1, f'<polyline points="{pts}" fill="none" stroke="{c2}" stroke-width="{wd}"/>')
    for k, (nm, val) in enumerate(prm):
        x, y, w, h = p.areas[f"LBL{k + 1}_{i + 1}"]
        put(nm, x + w / 2, y + 1.4, 1.4, wl.TXT, 700)
        put(val, x + w / 2, y + 3.6, 1.35, wl.DIM, 600)
x, y, w, h = p.areas["DISPLAY"]
put("FX 1 – 4", x + 3, y + 4.6, 3.4, "#ffffff", 800, "start", 0.2)
put("●  LINKED TO WING-LINK  ·  SYNC: RACK TEMPO", x + 3, y + 8.1, 1.5, "#b8f23a", 700, "start", 0.2)
put("CLOCK IN 16THS  ·  FX 2 TIME = 1/4", x + 3, y + 10.2, 1.4, wl.DIM, 600, "start", 0.2)
x, y, w, h = p.areas["STEP"]
put("4", x + w / 2, y + 4.4, 3.0, "#ffffff", 800)
x, y, w, h = p.areas["TEMPO"]
put("124.0", x + w / 2, y + 4.8, 2.6, "#ffffff", 800)
svg = sys.argv[2].rsplit(".", 1)[0] + ".svg"
open(svg, "w").write("\n".join(o))
subprocess.run(["rsvg-convert", "-w", "1400", svg, "-o", sys.argv[2]], check=True)
os.remove(svg)
print("wrote", sys.argv[2])
